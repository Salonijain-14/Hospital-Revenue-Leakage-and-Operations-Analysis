    (SELECT ROUND(100.0 * SUM(CASE WHEN status IN ('Cancelled', 'No-Show') THEN 1 ELSE 0 END) / COUNT(*), 2) FROM appointments) AS appointment_loss_rate_pct
FROM billing;

-- ANSWERING THE BUSINESS QUESTIONS :
-- 1.what is the total revenue generated by branch and medical specialization?
-- (identifying high performing branches and departments)
-- Calculates total paid revenue for each hospital branch and medical department.
SELECT 
    d.hospital_branch,
    d.specialization,
    SUM(b.amount) AS total_revenue
FROM billing b
JOIN hospitals.treatments t ON b.treatment_id = t.treatment_id
JOIN appointments a ON t.appointment_id = a.appointment_id
JOIN doctors d ON a.doctor_id = d.doctor_id
WHERE b.payment_status = 'Paid'
GROUP BY d.hospital_branch, d.specialization
ORDER BY total_revenue DESC;
-- RECOMMENDATIONS/INSIGHTS :
-- * Invest in Pediatrics: Highest revenue (52,623), making it the top-performing department.
-- * Improve Westside Oncology: Low revenue (1,075 vs. 18,935 at Eastside) indicates a need for operational review.
-- * Expand Dermatology at Eastside: Strong performance at other hospitals suggests high revenue potential.

-- 2.what is the total unpaid balance across insurance providers?
-- (pinpoints delayed insurance settlements and uncollected revenue)
-- Shows total pending money and unpaid bill counts grouped by insurance provider.
SELECT 
    p.insurance_provider,
    COUNT(b.bill_id) AS pending_bills,
    SUM(b.amount) AS  unpaid_amount
FROM billing b
JOIN treatments t ON b.treatment_id = t.treatment_id
JOIN appointments a ON t.appointment_id = a.appointment_id
JOIN patients p ON a.patient_id = p.patient_id
WHERE b.payment_status = 'Pending' or 'fail'
GROUP BY p.insurance_provider
ORDER BY unpaid_amount DESC;
-- RECOMMENDATIONS/INSIGHTS :
-- * Prioritize MedCare Plus: Follow up on 27 unpaid bills worth 68,255.
-- * Review WellnessCorp Claims: Check 17 high-value pending claims totaling 52,020.
-- * Verify Insurance Early: Confirm coverage at registration to reduce unpaid bills and payment delays.

-- Operational and doctor productivity analysis
-- 3. what is the appointments completion rate versus cancellation/ no-show rate per doctor?
-- Calculates completion and cancellation percentages for every doctor.
SELECT 
    d.doctor_id AS doctor_id,
    CONCAT(d.first_name, ' ', d.last_name) AS doctor_name,
    COUNT(a.appointment_id) AS total_appointments,
    ROUND(100.0 * SUM(CASE WHEN a.status = 'Completed' THEN 1 ELSE 0 END) / COUNT(a.appointment_id), 2) AS completion_rate_pct,
    ROUND(100.0 * SUM(CASE WHEN a.status IN ('Cancelled', 'No-Show') THEN 1 ELSE 0 END) / COUNT(a.appointment_id), 2) AS cancellation_rate_pct
FROM doctors d
LEFT JOIN appointments a ON d.doctor_id = a.doctor_id
GROUP BY d.doctor_id, d.first_name, d.last_name
ORDER BY cancellation_rate_pct DESC;
-- RECOMMENDATIONS/INSIGHTS :
-- * Send Appointment Reminders: Use SMS/WhatsApp reminders for doctors with high cancellation rates like Linda Brown,David taylor etc.
-- * Review Sarah Taylor's Schedule: Check why her completion rate is low despite having the highest appointments.
-- * Optimize High-Cancellation Slots: Slightly overbook doctors with frequent cancellations to reduce empty appointment slots.

-- 4.which treatment types that got the highest average cost and volume?
-- Counts total procedures, average cost, and overall revenue for each treatment type.
SELECT 
    treatment_type,
    COUNT(treatment_id) AS total_procedures,
    ROUND(AVG(cost), 2) AS avg_treatment_cost,
    SUM(cost) AS total_treatment_revenue
FROM treatments
GROUP BY treatment_type
ORDER BY total_treatment_revenue DESC;
-- RECOMMENDATIONS/INSIGHTS :
-- * Prioritize MRI Maintenance: Keep MRI services running to protect high-value revenue.
-- * Expand Chemotherapy Capacity: Add chairs or nursing support to meet high demand.
-- * Bundle X-Rays & ECGs: Offer combined diagnostic packages to increase revenue.
 
-- 5.what is patient retention rate?
-- (percentage of returning patients vs single-visit patients)?
-- eveluates patient loyalty and long term care continuity
-- Calculates the percentage of returning patients (more than 1 visit) versus single-visit patients.
WITH patient_visits AS (
    SELECT 
        patient_id, 
        COUNT(appointment_id) AS visit_count 
    FROM appointments
    WHERE status = 'Completed'
    GROUP BY patient_id)
SELECT 
    COUNT(CASE WHEN visit_count > 1 THEN 1 END) AS returning_patients,
    COUNT(CASE WHEN visit_count = 1 THEN 1 END) AS single_visit_patients,
    ROUND(100.0 * COUNT(CASE WHEN visit_count > 1 THEN 1 END) / COUNT(*), 2) AS retention_rate_pct
FROM patient_visits;
-- RECOMMENDATIONS :
-- * Send Follow-Up Reminders: Contact one-time patients after 30 days to encourage repeat visits.
-- * Collect Patient Feedback: Survey one-time visitors to understand why they did not return.
-- * Boost Patient Retention: Offer check-up packages or loyalty benefits to increase repeat visits.

-- 6.what is the rank of each doctor based on their total revenue?
-- Ranks doctors from highest to lowest based on total billing revenue generated.
SELECT 
    d.doctor_id,
    d.first_name,
    SUM(b.amount) AS total_revenue,
    RANK() OVER (ORDER BY SUM(b.amount) DESC) AS revenue_rank
FROM billing b
JOIN treatments t 
    ON b.treatment_id= t.treatment_id
JOIN appointments a 
    ON t.appointment_id = a.appointment_id
JOIN doctors d 
    ON a.doctor_id = d.doctor_id
GROUP BY d.doctor_id, d.first_name;
-- RECOMMENDATIONS/INSIGHTS :
-- * Support Top Performer Sarah: Optimize her schedule with admin support to maximize revenue.
-- * Share Best Practices: Let lower-performing doctors learn from the top three earners.
-- * Balance Patient Scheduling: Distribute high-value appointments more evenly across doctors.

-- 7.How can we segment our patient population by age to design targeted healthcare packages and preventive check-up programs?
-- Categorizes every patient into Minor, Adult, or Senior based on their age.
SELECT first_name, last_name, date_of_birth,
TIMESTAMPDIFF(YEAR, date_of_birth, CURDATE()) AS age,
CASE
    WHEN TIMESTAMPDIFF(YEAR, date_of_birth, CURDATE()) < 18 THEN 'Child'
    WHEN TIMESTAMPDIFF(YEAR, date_of_birth, CURDATE()) BETWEEN 18 AND 64 THEN 'Adult'
    ELSE 'Senior'
END AS age_group
FROM patients;
-- RECOMMENDATIONS/INSIGHTS :
-- * Launch Adult Screening Packages: Offer preventive check-ups for adults aged 35–64.
-- * Introduce Senior Care Plans: Provide specialized health packages for patients aged 65+.
-- * Send Milestone Health Reminders: Automate check-up alerts for ages 40, 50, and 65.


-- 8.which treatment got mostly claimed by insurance by patients and what is the total amount?
-- Finds the single treatment type with the highest total amount billed to insurance.
SELECT 
    t.treatment_type,
    COUNT(b.bill_id) AS total_claims,
    SUM(b.amount) AS total_claimed_amount
FROM billing b
JOIN treatments t 
    ON b.treatment_id = t.treatment_id
WHERE b.payment_method = 'Insurance' and payment_status = 'paid'
GROUP BY t.treatment_type
ORDER BY total_claimed_amount DESC
LIMIT 1;
-- RECOMMENDATIONS/INSIGHTS :
-- * Speed Up MRI Approvals: Simplify insurance pre-authorization for faster approvals.
-- * Improve MRI Claim Processing: Create a dedicated billing process for quicker reimbursements.
-- * Promote Insurance Coverage: Inform patients that insurance may cover MRI costs.

-- 9.Which top 3 insurance providers represent the highest outstanding paid balances for the hospital?
-- Finds the top 3 insurance providers with the highest total insurance billing amounts.
SELECT 
    p.patient_id,
    p.first_name,
    p.last_name,
    p.insurance_provider,
    SUM(b.amount) AS total_insurance_amount
FROM billing b
JOIN treatments t ON b.treatment_id = t.treatment_id
JOIN appointments a ON t.appointment_id = a.appointment_id
JOIN patients p ON a.patient_id = p.patient_id
WHERE b.payment_method = 'Insurance' and b.payment_status = 'paid'
GROUP BY p.patient_id, p.first_name, p.last_name, p.insurance_provider
ORDER BY total_insurance_amount DESC
LIMIT 3;
-- RECOMMENDATIONS/INSIGHTS :
-- * Support High-Value Patients: Assign case managers to ensure smooth care and paperwork.
-- * Audit Top Accounts: Review billing records to prevent claim delays.
-- * Offer Payment Counseling: Help patients manage deductibles and uncovered costs.

-- 10.How do unpaid insurance claim rates and payment delays vary across different patient age demographics?
-- Summarizes total insurance claim count and payout amount across 4 age groups.
SELECT 
    CASE 
        WHEN TIMESTAMPDIFF(YEAR, p.date_of_birth, CURDATE()) < 18 THEN 'Minor (Under 18)'
        WHEN TIMESTAMPDIFF(YEAR, p.date_of_birth, CURDATE()) BETWEEN 18 AND 35 THEN 'Young Adult (18-35)'
        WHEN TIMESTAMPDIFF(YEAR, p.date_of_birth, CURDATE()) BETWEEN 36 AND 60 THEN 'Middle Aged (36-60)'
        ELSE 'Senior (60+)'
    END AS age_group,
    COUNT(b.bill_id) AS total_claims,
    SUM(b.amount) AS total_unpaid_amount
FROM billing b
JOIN treatments t ON b.treatment_id = t.treatment_id
JOIN appointments a ON t.appointment_id = a.appointment_id
JOIN patients p ON a.patient_id = p.patient_id
WHERE b.payment_method = 'Insurance' 
  AND b.payment_status IN ('pending', 'failed')
GROUP BY age_group
ORDER BY total_unpaid_amount DESC;
-- RECOMMENDATIONS/INSIGHTS :
-- * Prioritize Young Adults: Focus on 18–35-year-olds, who have over $54,475 in unpaid revenue.
-- * Automate Insurance Checks: Verify insurance and pre-authorization digitally at checkout to prevent claim failures.
-- * Support Seniors: Provide billing help to patients with age 60+ to resolve insurance issues and reduce unpaid balance.


