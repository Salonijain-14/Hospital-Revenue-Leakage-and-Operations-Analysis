SELECT 
    CONCAT('$', FORMAT(SUM(amount), 2)) AS gross_billed_revenue,
    CONCAT('$', FORMAT(SUM(CASE WHEN payment_status = 'Paid' THEN amount ELSE 0 END), 2)) AS total_collected_revenue,
    CONCAT('$', FORMAT(SUM(CASE WHEN payment_status = 'Pending' THEN amount ELSE 0 END), 2)) AS total_unpaid_leakage,
